/// The Lean modules the generated runners import, beyond `Dashboard.Export`:
/// the manifest, every API, every frame, `Tests` when present and every
/// `Tests/*.lean`.
fn runner_modules(root: &Path) -> Vec<String> {
    let mut out = vec!["Architecture".to_string()];
    out.extend(api_files(root).into_iter().map(|a| format!("Apis.«{a}»")));
    out.extend(frame_files(root).into_iter().map(|m| format!("Frames.«{m}»")));
    if root.join(config::TESTS_LEAN).is_file() {
        out.push("Tests".to_string());
    }
    out.extend(tests_files(root).into_iter().map(|t| format!("Tests.«{t}»")));
    out
}

/// What the exporter produced.
#[derive(Debug, Default)]
pub struct Exported {
    pub arch: ArchConfig,
    pub idls: BTreeMap<String, Idl>,
    /// The checks of `Tests.lean` and `Tests/*.lean`, plus each module's
    /// implicit `test_cmd` check, and the `suite where` block.
    pub suite: config::Suite,
    /// The raw document, for the budget-raise diff (`raise::judge`).
    pub json: serde_json::Value,
}

fn lake() -> PathBuf {
    if let Some(home) = std::env::var_os("HOME") {
        let p = Path::new(&home).join(".elan/bin/lake");
        if p.is_file() {
            return p;
        }
    }
    PathBuf::from("lake")
}

/// The `lake build <modules> && lake env lean <runner>` command line, with
/// elan's binaries on PATH. Building exactly the runner's imports keeps a
/// package without `Apis/` or `Tests.lean` buildable.
fn export_cmd(modules: &[String], runner: &str) -> String {
    let lake = lake();
    let bin = lake.parent().map(|p| p.display().to_string()).unwrap_or_default();
    let targets: Vec<String> =
        std::iter::once("Dashboard.Export").chain(modules.iter().map(|m| m.as_str())).map(|m| format!("'+{m}'")).collect();
    format!(
        "export PATH=\"{bin}:$PATH\"; {lake} build {targets} >.lake/dashboard/build.log 2>&1 || {{ cat .lake/dashboard/build.log; exit 1; }}; \
         {lake} env lean {runner}",
        lake = lake.display(),
        targets = targets.join(" ")
    )
}

/// The last lines of a failed `lake` run, without its progress noise.
fn failure_tail(output: &std::process::Output) -> String {
    let mut all = String::from_utf8_lossy(&output.stdout).into_owned();
    all.push_str(&String::from_utf8_lossy(&output.stderr));
    let lines: Vec<&str> = all
        .lines()
        .filter(|l| !l.trim().is_empty() && !l.starts_with("info:") && !l.starts_with("trace:") && !l.starts_with("✔"))
        .collect();
    let tail: Vec<&str> = lines.iter().rev().take(20).rev().copied().collect();
    tail.join("\n")
}

/// Checks the package at `pkg` and its vendored files, seeds its build from
/// the Lake cache, writes `.lake/dashboard/<name>.lean` importing every
/// runner module and ending in `eval`, runs it jailed and returns the text
/// it wrote to `.lake/dashboard/<out>`.
fn run_lean(pkg: &Path, sandbox: &Sandbox, name: &str, eval: &str, out: &str) -> Result<String, String> {
    if !pkg.join("Architecture.lean").is_file() {
        return Err(format!("{}: no Architecture.lean", pkg.display()));
    }
    let root = pkg.parent().unwrap_or(pkg);
    // A differing copy could be another Lean version (and `lake` would go
    // and download it) or another DSL: the installed dashboard's is the one.
    let stale = drift(root);
    if !stale.is_empty() {
        return Err(format!(
            "{}: vendored dashboard library missing or differs from this dashboard's: run `dashboard arch gen`",
            stale.join(", ")
        ));
    }
    let scratch = pkg.join(".lake/dashboard");
    std::fs::create_dir_all(&scratch).map_err(|e| format!("{}: {e}", scratch.display()))?;
    let out = scratch.join(out);
    let _ = std::fs::remove_file(&out);
    let modules = runner_modules(root);
    let mut runner = String::from("import Dashboard.Export\n");
    for m in &modules {
        runner.push_str(&format!("import {m}\n"));
    }
    runner.push_str(eval);
    runner.push('\n');
    let file = format!(".lake/dashboard/{name}.lean");
    std::fs::write(pkg.join(&file), runner).map_err(|e| e.to_string())?;
    seed_build(pkg);
    let output = sandbox.command(&export_cmd(&modules, &file), pkg).output().map_err(|e| format!("lake: {e}"))?;
    match std::fs::read_to_string(&out) {
        Ok(t) if output.status.success() => {
            save_build(pkg);
            Ok(t)
        }
        _ => Err(format!("lean {} failed:\n{}", name.to_lowercase(), failure_tail(&output))),
    }
}

/// Where fresh packages' `.lake/build` is seeded from (spec decision 12):
/// `$DASHBOARD_LAKE_CACHE`, else `$XDG_CACHE_HOME/dashboard/lake/<hash>`
/// (`~/.cache` without it), keyed by the vendored files and the toolchain.
pub fn lake_cache_dir() -> Option<PathBuf> {
    if let Some(d) = std::env::var_os("DASHBOARD_LAKE_CACHE") {
        return Some(PathBuf::from(d));
    }
    let base = std::env::var_os("XDG_CACHE_HOME")
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("HOME").map(|h| Path::new(&h).join(".cache")))?;
    // FNV-1a: stable across builds, unlike `DefaultHasher`.
    let mut h: u64 = 0xcbf29ce484222325;
    let mut feed = |bytes: &[u8]| {
        for b in bytes.iter().chain([0u8].iter()) {
            h ^= *b as u64;
            h = h.wrapping_mul(0x100000001b3);
        }
    };
    for (rel, text) in vendored() {
        feed(rel.as_bytes());
        feed(text.as_bytes());
    }
    feed(TOOLCHAIN.as_bytes());
    let hex = format!("{h:016x}");
    Some(base.join("dashboard/lake").join(hex))
}

/// Copies the cached build into a package that has none. Lake decides
/// freshness by content hashes, so the copy is a hit for the vendored
/// library and a miss (rebuilt) for anything else.
fn seed_build(pkg: &Path) {
    let build = pkg.join(".lake/build");
    let Some(cache) = lake_cache_dir() else { return };
    if build.exists() || !cache.join("build").is_dir() {
        return;
    }
    let _ = Command::new("cp").arg("-a").arg(cache.join("build")).arg(pkg.join(".lake")).status();
}

/// After a successful build, fills an empty cache with the package's build.
/// Written to a temporary sibling and renamed, so concurrent writers never
/// leave a half copy behind.
fn save_build(pkg: &Path) {
    let Some(cache) = lake_cache_dir() else { return };
    if cache.join("build").is_dir() || !pkg.join(".lake/build").is_dir() {
        return;
    }
    static SEQ: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);
    let seq = SEQ.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    let tmp = cache.with_extension(format!("tmp{}-{seq}", std::process::id()));
    let _ = std::fs::remove_dir_all(&tmp);
    if std::fs::create_dir_all(&tmp).is_err() {
        return;
    }
    let ok = Command::new("cp").arg("-a").arg(pkg.join(".lake/build")).arg(&tmp).status().is_ok_and(|s| s.success());
    if ok {
        let _ = std::fs::create_dir_all(cache.parent().unwrap_or(&cache));
        if std::fs::rename(&tmp, &cache).is_err() {
            let _ = std::fs::remove_dir_all(&tmp);
        }
    } else {
        let _ = std::fs::remove_dir_all(&tmp);
    }
}

/// Runs the exporter in the package at `pkg` (`<root>/architecture`), jailed
/// if `sandbox` is on, and reads what it wrote. `lake` builds the package
/// (its `.lake/` cache makes a re-export of an unchanged tree fast) and then
/// elaborates a generated runner that imports every `Apis/*.lean` and calls
/// `Dashboard.exportTo`.
pub fn export(pkg: &Path, sandbox: &Sandbox) -> Result<Exported, String> {
    let text = run_lean(pkg, sandbox, "Export", "#eval Dashboard.exportTo \".lake/dashboard/arch.json\"", "arch.json")?;
    parse(&text)
}

/// The run set of `modules` (spec §6.6), as check names in suite order:
/// Lean's `Dashboard.impacted` over the package at `pkg`. An unknown name
/// is a Lean error, returned as the output's tail.
pub fn impacted(pkg: &Path, sandbox: &Sandbox, modules: &[String]) -> Result<Vec<String>, String> {
    let nodes: Vec<String> = modules.iter().map(|m| format!("({} : Dashboard.Node)", ident(m))).collect();
    let eval = format!("#eval Dashboard.impactedTo \".lake/dashboard/impacted.json\" [{}]", nodes.join(", "));
    let text = run_lean(pkg, sandbox, "Impacted", &eval, "impacted.json")?;
    serde_json::from_str(&text).map_err(|e| format!("impacted: {e}"))
}

/// Parses an export document (`{"arch": ..., "idls": {...}, "errors": [...]}`),
/// validating the manifest and every IDL.
pub fn parse(text: &str) -> Result<Exported, String> {
    let json: serde_json::Value = serde_json::from_str(text).map_err(|e| format!("export: {e}"))?;
    if let Some(errs) = json.get("errors").and_then(|e| e.as_array())
        && !errs.is_empty()
    {
        return Err(errs.iter().map(|e| e.as_str().unwrap_or("export error")).collect::<Vec<_>>().join("\n"));
    }
    let mut arch = config::arch_config_from_json(json.get("arch").cloned().unwrap_or_default())
        .map_err(|e| format!("Architecture.lean: {e}"))?;
    if let Some(frames) = json.get("frames") {
        arch.frames = serde_json::from_value(frames.clone()).map_err(|e| format!("frames: {e}"))?;
    }
    // A frame's skeleton and holes are written under its `src`: inside its
    // own module, so a frame never opens another module's files.
    for f in &arch.frames {
        let file = crate::frame::lean_file(&f.module);
        let Some(m) = arch.modules.iter().find(|m| m.name == f.module) else {
            return Err(format!("{file}: frame of {}, which is no module", f.module));
        };
        let src = f.src.trim_end_matches('/');
        if src.is_empty() || src.starts_with('/') || src.split('/').any(|c| c == ".." || c == ".") || !config::path_under_test_paths(src, &m.paths) {
            return Err(format!("{file}: src {:?} must be a directory inside module {}'s paths", f.src, m.name));
        }
    }
    // Every API's every problem, not just the first.
    let mut idls = BTreeMap::new();
    let mut errs = Vec::new();
    if let Some(map) = json.get("idls").and_then(|i| i.as_object()) {
        for (name, v) in map {
            match serde_json::from_value(v.clone()).map_err(|e| e.to_string()).and_then(Idl::from_export) {
                Ok(idl) => {
                    idls.insert(name.clone(), idl);
                }
                Err(e) => errs.extend(e.lines().map(|l| format!("{}: {l}", api_file(name)))),
            }
        }
    }
    if !errs.is_empty() {
        return Err(errs.join("\n"));
    }
    for a in &arch.apis {
        if !idls.contains_key(&a.name) {
            return Err(format!("api {}: no `idl {}` block (expected {})", a.name, a.name, api_file(&a.name)));
        }
    }
    for name in idls.keys() {
        if !arch.apis.iter().any(|a| a.name == *name) {
            return Err(format!("{}: idl for an api the manifest does not declare", api_file(name)));
        }
    }
    let suite = parse_suite(&json, &arch)?;
    Ok(Exported { arch, idls, suite, json })
}

/// The file of a check's declaring Lean module (`Tests/x.worker` →
/// `architecture/Tests/x.worker.lean`).
fn source_of(module: &str) -> String {
    format!("{DIR}/{module}.lean")
}

/// The suite of an export: its checks (each validated, with `source` from
/// its declaring module), then one implicit check per module with a
/// `test_cmd`. Names are unique; a check covers something.
fn parse_suite(json: &serde_json::Value, arch: &ArchConfig) -> Result<config::Suite, String> {
    #[derive(serde::Deserialize, Default)]
    #[serde(default)]
    struct Block {
        test_paths: Vec<String>,
        list_cmd: Option<String>,
    }
    let block: Block = match json.get("suite") {
        Some(v) => serde_json::from_value(v.clone()).map_err(|e| format!("suite: {e}"))?,
        None => Block::default(),
    };
    let mut checks = Vec::new();
    for v in json.get("checks").and_then(|c| c.as_array()).into_iter().flatten() {
        let mut c: config::Check = serde_json::from_value(v.clone()).map_err(|e| format!("check: {e}"))?;
        let source = source_of(v.get("module").and_then(|m| m.as_str()).unwrap_or("Tests"));
        c.validate().map_err(|e| format!("{source}: {e}"))?;
        if !c.all && c.covers.is_empty() {
            return Err(format!("{source}: check {:?}: covers is empty: write covers = all or covers = [module, …]", c.name));
        }
        c.source = Some(source);
        checks.push(c);
    }
    let mut out: Vec<config::Check> = Vec::new();
    for c in checks {
        if arch.modules.iter().any(|m| m.name == c.name) {
            return Err(format!("{}: check {:?} is named like a module", c.source.as_deref().unwrap_or(""), c.name));
        }
        if out.iter().any(|o| o.name == c.name) {
            return Err(format!("check name {:?} is declared more than once", c.name));
        }
        out.push(c);
    }
    // A check's `files` leave its file out of every other check's view, and
    // a task agent and a worker may add files under their checks' `files`:
    // over a fixture, either would reach into setup its users share.
    let overlap = |a: &str, b: &str| {
        let (a, b) = (a.trim_end_matches('/'), b.trim_end_matches('/'));
        config::path_under_test_paths(a, &[b.to_string()]) || config::path_under_test_paths(b, &[a.to_string()])
    };
    for f in &arch.fixtures {
        for p in &f.paths {
            if let Some(t) = block.test_paths.iter().find(|t| overlap(p, t)) {
                return Err(format!("{}: test_paths {t:?} overlaps fixture {}'s {p:?}", config::TESTS_LEAN, f.name));
            }
            for c in &out {
                if let Some(x) = c.files.iter().find(|x| overlap(p, x)) {
                    return Err(format!(
                        "{}: check {:?}: files {x:?} overlaps fixture {}'s {p:?}: a fixture's files are its own; a check reads them through its covers",
                        c.source.as_deref().unwrap_or(""),
                        c.name,
                        f.name
                    ));
                }
            }
        }
    }
    for m in &arch.modules {
        if let Some(cmd) = &m.test_cmd {
            out.push(config::Check {
                name: m.name.clone(),
                cmd: cmd.clone(),
                covers: vec![m.name.clone()],
                source: Some(config::ARCH_LEAN_MANIFEST.to_string()),
                ..config::Check::default()
            });
        }
    }
    Ok(config::Suite { checks: out, test_paths: block.test_paths, list_cmd: block.list_cmd })
}

/// Exports `architecture/` trees of a hub in one package directory
/// (`<home>/arch`), whose `.lake/` build cache survives between trees.
#[derive(Debug, Clone)]
pub struct Exporter {
    dir: PathBuf,
    sandbox: Sandbox,
}

impl Exporter {
    pub fn new(dir: PathBuf, sandbox: Sandbox) -> Self {
        Exporter { dir, sandbox }
    }

    pub fn set_sandbox(&mut self, sandbox: Sandbox) {
        self.sandbox = sandbox;
    }

    /// Materializes `tree` (an `architecture/` tree id of `hub`) as
    /// `<dir>/architecture`, keeping its `.lake/`, and returns the package.
    fn checkout(&self, hub: &crate::git::Git, tree: &str) -> Result<PathBuf, String> {
        let pkg = self.dir.join(DIR);
        if pkg.exists() {
            for e in std::fs::read_dir(&pkg).map_err(|e| e.to_string())?.flatten() {
                if e.file_name() != ".lake" {
                    let p = e.path();
                    if p.is_dir() { std::fs::remove_dir_all(&p) } else { std::fs::remove_file(&p) }.map_err(|e| e.to_string())?;
                }
            }
        }
        std::fs::create_dir_all(&pkg).map_err(|e| e.to_string())?;
        // Plain git, no `tar`: blob by blob, bytes as stored.
        let git = |args: &[&str]| -> Result<Vec<u8>, String> {
            let out = Command::new("git").arg("-C").arg(&hub.dir).args(args).output().map_err(|e| e.to_string())?;
            if out.status.success() {
                Ok(out.stdout)
            } else {
                Err(format!("git {}: {}", args.join(" "), String::from_utf8_lossy(&out.stderr).trim()))
            }
        };
        let listing = git(&["ls-tree", "-r", "-z", tree])?;
        for entry in listing.split(|b| *b == 0).filter(|e| !e.is_empty()) {
            let entry = String::from_utf8_lossy(entry);
            let Some((meta, path)) = entry.split_once('\t') else { continue };
            let mut parts = meta.split(' ');
            let (_, kind, sha) = (parts.next(), parts.next(), parts.next().unwrap_or_default());
            if kind != Some("blob") {
                continue;
            }
            let dest = pkg.join(path);
            std::fs::create_dir_all(dest.parent().unwrap()).map_err(|e| e.to_string())?;
            std::fs::write(&dest, git(&["cat-file", "blob", sha])?).map_err(|e| format!("{}: {e}", dest.display()))?;
        }
        Ok(pkg)
    }

    /// The export of `tree`.
    pub fn export_tree(&self, hub: &crate::git::Git, tree: &str) -> Result<Exported, String> {
        export(&self.checkout(hub, tree)?, &self.sandbox)
    }

    /// The run set of `modules` in `tree`.
    pub fn impacted_tree(&self, hub: &crate::git::Git, tree: &str, modules: &[String]) -> Result<Vec<String>, String> {
        impacted(&self.checkout(hub, tree)?, &self.sandbox, modules)
    }
}

/// `lake` is on this host (needed to load a Lean architecture at all).
pub fn available() -> bool {
    Command::new(lake()).arg("--version").output().is_ok_and(|o| o.status.success())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_an_export_and_cross_checks_apis_against_idls() {
        let doc = r#"{"arch": {"max_modules": 2, "module": [{"name": "a", "lang": "rust", "paths": ["a"]}, {"name": "b", "lang": "rust", "paths": ["b"]}],
            "api": [{"name": "ab", "generator": "a", "consumer": "b", "paths": ["api"]}]},
            "idls": {"ab": {"api": "ab", "types": [{"name": "Id", "kind": {"repr": "i64"}}], "ctors": [{"name": "X", "args": ["Id"]}]}},
            "errors": []}"#;
        let e = parse(doc).unwrap();
        assert_eq!(e.arch.modules.len(), 2);
        assert_eq!(e.idls["ab"].constructors(), 1);
        let missing = doc.replace(r#""idls": {"ab":"#, r#""idls": {"xy":"#).replace(r#""api": "ab", "types""#, r#""api": "xy", "types""#);
        assert!(parse(&missing).unwrap_err().contains("no `idl ab` block"), "{}", parse(&missing).unwrap_err());
        let errs = doc.replace(r#""errors": []"#, r#""errors": ["api ab: more than one `idl` block"]"#);
        assert!(parse(&errs).unwrap_err().contains("more than one"));
        let bad = doc.replace(r#""consumer": "b""#, r#""consumer": "zz""#);
        assert!(parse(&bad).unwrap_err().contains("unknown module or root"));
    }

    #[test]
    fn vendored_files_drift() {
        let d = tempfile::tempdir().unwrap();
        assert_eq!(drift(d.path()).len(), vendored().len());
        let wrote = write_vendored(d.path()).unwrap();
        assert_eq!(wrote.len(), vendored().len());
        assert!(drift(d.path()).is_empty());
        std::fs::write(d.path().join("architecture/lean-toolchain"), "other\n").unwrap();
        assert_eq!(drift(d.path()), ["architecture/lean-toolchain"]);
        assert_eq!(write_vendored(d.path()).unwrap(), ["architecture/lean-toolchain"]);
    }

    #[test]
    fn quotes_dsl_and_lean_keywords() {
        for k in ["store", "display", "ref", "v", "permanent", "container", "idl", "where", "fun", "check", "suite"] {
            assert_eq!(ident(k), format!("«{k}»"), "{k}");
        }
        assert_eq!(ident("db"), "db");
        assert_eq!(ident("engine-client"), "«engine-client»");
    }

    #[test]
    fn a_check_keeps_its_files_and_test_paths_apart_from_fixtures() {
        let doc = |files: &str, test_paths: &str| {
            format!(
                r#"{{"arch": {{"module": [{{"name": "a", "lang": "rust", "paths": ["a"]}}],
                "fixture": [{{"name": "heroes", "users": ["a"], "paths": ["fixtures/heroes"]}}]}},
                "idls": {{}}, "suite": {{"test_paths": {test_paths}}},
                "checks": [{{"name": "t", "cmd": "true", "covers": ["a"], "files": {files}, "module": "Tests/x"}}], "errors": []}}"#
            )
        };
        assert!(parse(&doc(r#"["a/tests/t.rs"]"#, "[]")).is_ok());
        let e = parse(&doc(r#"["fixtures/heroes/x.rs"]"#, "[]")).unwrap_err();
        assert!(e.contains("architecture/Tests/x.lean: check \"t\": files \"fixtures/heroes/x.rs\" overlaps fixture heroes"), "{e}");
        assert!(parse(&doc(r#"["fixtures"]"#, "[]")).unwrap_err().contains("overlaps fixture heroes"));
        assert!(parse(&doc("[]", r#"["fixtures/heroes"]"#)).unwrap_err().contains("test_paths"));
    }
}
