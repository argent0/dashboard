// The Lean architecture (handover §0): a project's `architecture/` is a Lake
// package holding the manifest (`Architecture.lean`: modules, roots, APIs,
// budgets) and one IDL per API (`Apis/<name>.lean`), written in the DSL of
// `src/lean/Dashboard.lean`. That library is vendored into the package (this
// binary's copy is the source of truth; a differing copy is drift) and
// `src/lean/Export.lean` walks the elaborated declarations into one JSON
// document, which `config::ArchConfig` and `idl::Idl` deserialize. Lean type-
// checks the design (a module an API names must be declared, a ref'd type
// must exist, a field must be a field); everything that acts on real code
// stays in Rust.

use crate::config::{self, ArchConfig};
use crate::idl::Idl;
use crate::sandbox::Sandbox;
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::Command;

/// The package directory inside a project.
pub const DIR: &str = config::ARCH_DIR;
/// The Lean the vendored library was written against: `elan` installs it
/// on first use.
pub const TOOLCHAIN: &str = "leanprover/lean4:v4.35.0";

const DASHBOARD_LEAN: &str = include_str!("lean/Dashboard.lean");
const EXPORT_LEAN: &str = include_str!("lean/Export.lean");
const LAKEFILE: &str = "\
# Generated by `dashboard arch gen`; do not edit.
name = \"architecture\"
defaultTargets = [\"Dashboard\", \"Architecture\", \"Apis\"]

[[lean_lib]]
name = \"Dashboard\"
roots = [\"Dashboard\", \"Dashboard.Export\"]

[[lean_lib]]
name = \"Architecture\"

[[lean_lib]]
name = \"Apis\"
globs = [\"Apis.+\"]
";
const GITIGNORE: &str = ".lake/\nlake-manifest.json\n";

/// The files `dashboard` owns inside the package, relative to it.
pub fn vendored() -> Vec<(&'static str, String)> {
    vec![
        ("Dashboard.lean", DASHBOARD_LEAN.to_string()),
        ("Dashboard/Export.lean", EXPORT_LEAN.to_string()),
        ("lakefile.toml", LAKEFILE.to_string()),
        ("lean-toolchain", format!("{TOOLCHAIN}\n")),
        (".gitignore", GITIGNORE.to_string()),
    ]
}

/// Whether `root` has a Lean architecture (`architecture/Architecture.lean`).
pub fn present(root: &Path) -> bool {
    root.join(config::ARCH_LEAN_MANIFEST).is_file()
}

/// The vendored files whose copy under `root/architecture/` is missing or
/// differs, as paths relative to `root`.
pub fn drift(root: &Path) -> Vec<String> {
    vendored()
        .into_iter()
        .filter(|(rel, want)| std::fs::read_to_string(root.join(DIR).join(rel)).ok().as_deref() != Some(want.as_str()))
        .map(|(rel, _)| format!("{DIR}/{rel}"))
        .collect()
}

/// Writes every vendored file that is missing or differs; returns what it wrote.
pub fn write_vendored(root: &Path) -> Result<Vec<String>, String> {
    let mut wrote = Vec::new();
    for (rel, want) in vendored() {
        let path = root.join(DIR).join(rel);
        if std::fs::read_to_string(&path).ok().as_deref() == Some(want.as_str()) {
            continue;
        }
        std::fs::create_dir_all(path.parent().unwrap()).map_err(|e| format!("{}: {e}", path.display()))?;
        std::fs::write(&path, &want).map_err(|e| format!("{}: {e}", path.display()))?;
        wrote.push(format!("{DIR}/{rel}"));
    }
    Ok(wrote)
}

/// `architecture/Apis/<name>.lean` for API `name`.
pub fn api_file(name: &str) -> String {
    format!("{DIR}/Apis/{name}.lean")
}

/// The API names with an IDL file under `architecture/Apis/`, sorted.
pub fn api_files(root: &Path) -> Vec<String> {
    let mut out = Vec::new();
    if let Ok(rd) = std::fs::read_dir(root.join(DIR).join("Apis")) {
        for e in rd.flatten() {
            let name = e.file_name().to_string_lossy().into_owned();
            if let Some(stem) = name.strip_suffix(".lean")
                && e.path().is_file()
            {
                out.push(stem.to_string());
            }
        }
    }
    out.sort();
    out
}

/// What the exporter produced.
#[derive(Debug, Default)]
pub struct Exported {
    pub arch: ArchConfig,
    pub idls: BTreeMap<String, Idl>,
    /// The raw document, for the budget-raise diff (`raise::judge`).
    pub json: serde_json::Value,
}

fn lake() -> PathBuf {
    if let Some(home) = std::env::var_os("HOME") {
        let p = Path::new(&home).join(".elan/bin/lake");
        if p.is_file() {
            return p;
        }
    }
    PathBuf::from("lake")
}

/// The `lake build && lake env lean <runner>` command line, with elan's
/// binaries on PATH.
fn export_cmd(runner: &str) -> String {
    let lake = lake();
    let bin = lake.parent().map(|p| p.display().to_string()).unwrap_or_default();
    format!(
        "export PATH=\"{bin}:$PATH\"; {lake} build >.lake/dashboard/build.log 2>&1 || {{ cat .lake/dashboard/build.log; exit 1; }}; \
         {lake} env lean {runner}",
        lake = lake.display()
    )
}

/// Runs the exporter in the package at `pkg` (`<root>/architecture`), jailed
/// if `sandbox` is on, and reads what it wrote. `lake` builds the package
/// (its `.lake/` cache makes a re-export of an unchanged tree fast) and then
/// elaborates a generated runner that imports every `Apis/*.lean` and calls
/// `Dashboard.exportTo`.
pub fn export(pkg: &Path, sandbox: &Sandbox) -> Result<Exported, String> {
    if !pkg.join("Architecture.lean").is_file() {
        return Err(format!("{}: no Architecture.lean", pkg.display()));
    }
    let root = pkg.parent().unwrap_or(pkg);
    // A differing copy could be another Lean version (and `lake` would go
    // and download it) or another DSL: the installed dashboard's is the one.
    let stale = drift(root);
    if !stale.is_empty() {
        return Err(format!(
            "{}: vendored dashboard library missing or differs from this dashboard's: run `dashboard arch gen`",
            stale.join(", ")
        ));
    }
    let scratch = pkg.join(".lake/dashboard");
    std::fs::create_dir_all(&scratch).map_err(|e| format!("{}: {e}", scratch.display()))?;
    let out = scratch.join("arch.json");
    let _ = std::fs::remove_file(&out);
    let mut runner = String::from("import Dashboard.Export\nimport Architecture\n");
    for api in api_files(root) {
        runner.push_str(&format!("import Apis.«{api}»\n"));
    }
    runner.push_str("#eval Dashboard.exportTo \".lake/dashboard/arch.json\"\n");
    std::fs::write(scratch.join("Export.lean"), runner).map_err(|e| e.to_string())?;
    let output = sandbox
        .command(&export_cmd(".lake/dashboard/Export.lean"), pkg)
        .output()
        .map_err(|e| format!("lake: {e}"))?;
    let text = match std::fs::read_to_string(&out) {
        Ok(t) if output.status.success() => t,
        _ => {
            let mut all = String::from_utf8_lossy(&output.stdout).into_owned();
            all.push_str(&String::from_utf8_lossy(&output.stderr));
            let lines: Vec<&str> = all
                .lines()
                .filter(|l| !l.trim().is_empty() && !l.starts_with("info:") && !l.starts_with("trace:") && !l.starts_with("✔"))
                .collect();
            let tail: Vec<&str> = lines.iter().rev().take(20).rev().copied().collect();
            return Err(format!("lean export failed:\n{}", tail.join("\n")));
        }
    };
    parse(&text)
}

/// Parses an export document (`{"arch": ..., "idls": {...}, "errors": [...]}`),
/// validating the manifest and every IDL as the TOML/KDL loaders do.
pub fn parse(text: &str) -> Result<Exported, String> {
    let json: serde_json::Value = serde_json::from_str(text).map_err(|e| format!("export: {e}"))?;
    if let Some(errs) = json.get("errors").and_then(|e| e.as_array())
        && let Some(e) = errs.first()
    {
        return Err(e.as_str().unwrap_or("export error").to_string());
    }
    let arch = config::arch_config_from_json(json.get("arch").cloned().unwrap_or_default())
        .map_err(|e| format!("Architecture.lean: {e}"))?;
    let mut idls = BTreeMap::new();
    if let Some(map) = json.get("idls").and_then(|i| i.as_object()) {
        for (name, v) in map {
            let idl: Idl = serde_json::from_value(v.clone()).map_err(|e| format!("{}: {e}", api_file(name)))?;
            let idl = Idl::from_export(idl).map_err(|e| format!("{}: {e}", api_file(name)))?;
            idls.insert(name.clone(), idl);
        }
    }
    for a in &arch.apis {
        if !idls.contains_key(&a.name) {
            return Err(format!("api {}: no `idl {}` block (expected {})", a.name, a.name, api_file(&a.name)));
        }
    }
    for name in idls.keys() {
        if !arch.apis.iter().any(|a| a.name == *name) {
            return Err(format!("{}: idl for an api the manifest does not declare", api_file(name)));
        }
    }
    Ok(Exported { arch, idls, json })
}

/// `lake` is on this host (needed to load a Lean architecture at all).
pub fn available() -> bool {
    Command::new(lake()).arg("--version").output().is_ok_and(|o| o.status.success())
}

/// Writes the Lean package for a TOML manifest and its KDL IDLs (`dashboard
/// arch migrate`): the vendored library, `Architecture.lean` and one
/// `Apis/<name>.lean` per API. Returns the files written. Comments in the
/// TOML and KDL are not carried over.
pub fn migrate(root: &Path, cfg: &ArchConfig, idls: &BTreeMap<String, Idl>) -> Result<Vec<String>, String> {
    let mut wrote = write_vendored(root)?;
    let mut put = |rel: String, text: String| -> Result<(), String> {
        let path = root.join(&rel);
        std::fs::create_dir_all(path.parent().unwrap()).map_err(|e| e.to_string())?;
        std::fs::write(&path, text).map_err(|e| format!("{rel}: {e}"))?;
        wrote.push(rel);
        Ok(())
    };
    put(config::ARCH_LEAN_MANIFEST.to_string(), cfg.lean())?;
    for a in &cfg.apis {
        let Some(idl) = idls.get(&a.name) else { continue };
        put(api_file(&a.name), idl.lean())?;
    }
    Ok(wrote)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_an_export_and_cross_checks_apis_against_idls() {
        let doc = r#"{"arch": {"max_modules": 2, "module": [{"name": "a", "lang": "rust", "paths": ["a"]}, {"name": "b", "lang": "rust", "paths": ["b"]}],
            "api": [{"name": "ab", "generator": "a", "consumer": "b", "paths": ["api"]}]},
            "idls": {"ab": {"api": "ab", "types": [{"name": "Id", "kind": {"repr": "i64"}}], "ctors": [{"name": "X", "args": ["Id"]}]}},
            "errors": []}"#;
        let e = parse(doc).unwrap();
        assert_eq!(e.arch.modules.len(), 2);
        assert_eq!(e.idls["ab"].constructors(), 1);
        let missing = doc.replace(r#""idls": {"ab":"#, r#""idls": {"xy":"#).replace(r#""api": "ab", "types""#, r#""api": "xy", "types""#);
        assert!(parse(&missing).unwrap_err().contains("no `idl ab` block"), "{}", parse(&missing).unwrap_err());
        let errs = doc.replace(r#""errors": []"#, r#""errors": ["api ab: more than one `idl` block"]"#);
        assert!(parse(&errs).unwrap_err().contains("more than one"));
        let bad = doc.replace(r#""consumer": "b""#, r#""consumer": "zz""#);
        assert!(parse(&bad).unwrap_err().contains("unknown module or root"));
    }

    #[test]
    fn vendored_files_drift() {
        let d = tempfile::tempdir().unwrap();
        assert_eq!(drift(d.path()).len(), vendored().len());
        let wrote = write_vendored(d.path()).unwrap();
        assert_eq!(wrote.len(), vendored().len());
        assert!(drift(d.path()).is_empty());
        std::fs::write(d.path().join("architecture/lean-toolchain"), "other\n").unwrap();
        assert_eq!(drift(d.path()), ["architecture/lean-toolchain"]);
        assert_eq!(write_vendored(d.path()).unwrap(), ["architecture/lean-toolchain"]);
    }
}
